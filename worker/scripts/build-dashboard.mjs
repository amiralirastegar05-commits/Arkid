// Generate a single-file Cloudflare Dashboard deployment from the reviewed
// Worker and public configuration. Never put secret keys into wrangler.toml.
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const source = await readFile(new URL('src/index.js', root), 'utf8');
const toml = await readFile(new URL('wrangler.toml', root), 'utf8');
function config(name) {
  const matches = [...toml.matchAll(new RegExp(`^${name}\\s*=\\s*"([^"\\n]+)"\\s*$`, 'gm'))];
  if (matches.length !== 1) throw Error(`Expected exactly one ${name} in wrangler.toml`);
  return matches[0][1];
}
const settings = {
  SUPABASE_URL: config('SUPABASE_URL'),
  SUPABASE_PUBLISHABLE_KEY: config('SUPABASE_PUBLISHABLE_KEY'),
  ALLOWED_ORIGINS: config('ALLOWED_ORIGINS'),
};
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(settings.SUPABASE_URL) ||
    !/^sb_publishable_[A-Za-z0-9_-]+$/.test(settings.SUPABASE_PUBLISHABLE_KEY) ||
    !settings.ALLOWED_ORIGINS.split(',').every(origin => /^https:\/\/[a-z0-9.-]+$/i.test(origin))) {
  throw Error('Dashboard build requires a Supabase URL, a publishable key, and HTTPS origins only.');
}
const marker = 'export default {';
if (source.split(marker).length !== 2) throw Error('Unexpected Worker export format');
const output = `// Generated by worker/scripts/build-dashboard.mjs; do not edit by hand.\n// Configuration below contains only public values. Dashboard deployment uses\n// these fixed values, not Variables and Secrets in the Cloudflare dashboard.\n${source.replace(marker, 'const arkidWorker = {')}\nconst DASHBOARD_CONFIG = Object.freeze(${JSON.stringify(settings, null, 2)});\nexport default {\n  fetch(request) { return arkidWorker.fetch(request, DASHBOARD_CONFIG); },\n};\n`;
const path = new URL('dashboard-worker.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw Error('dashboard-worker.js is out of date');
  console.log('Dashboard Worker matches source and public settings.');
} else {
  await writeFile(path, output);
  console.log('Generated worker/dashboard-worker.js.');
}
